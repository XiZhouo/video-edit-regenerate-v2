"""Pure values for the audited cutover activation protocol v2.

Activation is the final, durable read-only-to-active state transition.  This
contract deliberately does not treat the phase-two value pre-generated by the
v1 cutover planner as permission to open writes.  A v2 issuer must instead
bind an exact installed/read-only row to a freshly classified INSTALL audit
certificate and to the current final file admission.

The types below do not open SQLite, inspect a path, acquire a lock, choose a
clock, or invoke a callback.  An activation plan is only an expectation; only
a freshly read generic receipt plus matching specialised evidence can prove
that the transition was persisted.
"""

