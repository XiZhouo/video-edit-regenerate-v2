class BusinessCutoverActivationContractError(ValueError):
    """Stable payload-free failure at the activation boundary."""

    __slots__ = ("code", "path")

    def __init__(self, code: str, path: str) -> None:
        if type(code) is not str or not code:
            raise TypeError("code must be a non-empty exact string")
        if type(path) is not str or not path:
            raise TypeError("path must be a non-empty exact string")
        self.code = code
        self.path = path
        super().__init__(code)


def _fail(code: str, path: str) -> None:
    raise BusinessCutoverActivationContractError(code, path)


def _text(
    value: Any,
    path: str,
    *,
    maximum: int = MAX_BUSINESS_CUTOVER_ACTIVATION_TEXT_BYTES,
) -> str:
    if type(value) is not str or not value:
        _fail("business_cutover_activation_text_invalid", path)
    try:
        encoded = value.encode("utf-8", "strict")
    except UnicodeEncodeError:
        _fail("business_cutover_activation_text_invalid", path)
        raise AssertionError("unreachable")
    if len(encoded) > maximum:
        _fail("business_cutover_activation_text_budget_exceeded", path)
    return value


def _integer(
    value: Any,
    path: str,
    *,
    minimum: int = 0,
    maximum: int = MAX_SQLITE_INTEGER,
) -> int:
    if type(value) is not int or not minimum <= value <= maximum:
        _fail("business_cutover_activation_integer_invalid", path)
    return value


def _lower_hex(value: Any, path: str, length: int) -> str:
    if (
        type(value) is not str
        or len(value) != length
        or any(character not in _LOWER_HEX for character in value)
    ):
        _fail("business_cutover_activation_hex_invalid", path)
    return value


def _digest(value: Any, path: str) -> bytes:
    if type(value) is not bytes or len(value) != 32:
        _fail("business_cutover_activation_digest_invalid", path)
    return value


def _timestamp(value: Any, path: str) -> str:
    if type(value) is not str or len(value) != 24:
        _fail("business_cutover_activation_timestamp_invalid", path)
    try:
        parsed = datetime.strptime(value, "%Y-%m-%dT%H:%M:%S.%fZ")
    except (TypeError, ValueError):
        _fail("business_cutover_activation_timestamp_invalid", path)
        raise AssertionError("unreachable")
    canonical = parsed.strftime("%Y-%m-%dT%H:%M:%S.") + (
        "%03dZ" % (parsed.microsecond // 1000)
    )
    if canonical != value:
        _fail("business_cutover_activation_timestamp_invalid", path)
    return value


def _runtime_identity(value: BusinessCutoverRuntimeBinding) -> tuple:
    return (
        value.authority,
        value.repository_epoch,
        value.cutover_id,
        value.source_admission_revision,
        value.repository_revision,
        value.runtime_generation,
        value.code_digest,
        value.schema_version,
    )


@dataclass(frozen=True)
class BusinessCutoverActivationPrerequisiteSnapshot:
    """Raw barrier/snapshot payload; it is not fresh without a reader stamp."""

    current_admission: BusinessCutoverAdmission
    observed_install: Optional[BusinessCutoverInstallEvidence]
    expected_migration_ledger_count: int
    expected_migration_ledger_sha256: bytes = field(repr=False)

    def __post_init__(self) -> None:
        if type(self.current_admission) is not BusinessCutoverAdmission:
            _fail(
                "business_cutover_activation_admission_invalid",
                "$.prerequisites.current_admission",
            )
        if self.observed_install is not None and type(
            self.observed_install
        ) is not BusinessCutoverInstallEvidence:
            _fail(
                "business_cutover_activation_install_invalid",
                "$.prerequisites.observed_install",
            )
        _integer(
            self.expected_migration_ledger_count,
            "$.prerequisites.expected_migration_ledger_count",
            minimum=1,
        )
        _digest(
            self.expected_migration_ledger_sha256,
            "$.prerequisites.expected_migration_ledger_sha256",
        )


class BusinessCutoverActivationCoordinatorReaderCapability:
    """Authority for the joint file-barrier and SQLite-install observation."""

    __slots__ = ("_issuer",)

    def __init__(self, *, _issuer: Any) -> None:
        if _issuer is not _COORDINATOR_READER_CAPABILITY_ISSUER:
            _fail(
                "business_cutover_activation_coordinator_reader_invalid",
                "$.coordinator_reader",
            )
        object.__setattr__(self, "_issuer", _issuer)

    def __setattr__(self, name: str, value: Any) -> None:
        del name, value
        raise AttributeError(
            "BusinessCutoverActivationCoordinatorReaderCapability is immutable"
        )


_BUSINESS_CUTOVER_ACTIVATION_COORDINATOR_READER_CAPABILITY = (
    BusinessCutoverActivationCoordinatorReaderCapability(
        _issuer=_COORDINATOR_READER_CAPABILITY_ISSUER
    )
)


class BusinessCutoverActivationFreshPrerequisites:
    """Coordinator-reader stamped admission and install from one barrier."""

    __slots__ = ("snapshot", "_reader", "_issuer")

    def __init__(
        self,
        snapshot: BusinessCutoverActivationPrerequisiteSnapshot,
        *,
        _reader: BusinessCutoverActivationCoordinatorReaderCapability,
        _issuer: Any,
    ) -> None:
        if (
            _issuer is not _FRESH_PREREQUISITE_ISSUER
            or _reader
            is not _BUSINESS_CUTOVER_ACTIVATION_COORDINATOR_READER_CAPABILITY
            or type(snapshot)
            is not BusinessCutoverActivationPrerequisiteSnapshot
        ):
            _fail(
                "business_cutover_activation_fresh_prerequisites_invalid",
                "$.prerequisites",
            )
        object.__setattr__(self, "snapshot", snapshot)
        object.__setattr__(self, "_reader", _reader)
        object.__setattr__(self, "_issuer", _issuer)

    def __setattr__(self, name: str, value: Any) -> None:
        del name, value
        raise AttributeError(
            "BusinessCutoverActivationFreshPrerequisites is immutable"
        )


def _stamp_business_cutover_activation_fresh_prerequisites(
    reader: BusinessCutoverActivationCoordinatorReaderCapability,
    snapshot: BusinessCutoverActivationPrerequisiteSnapshot,
) -> BusinessCutoverActivationFreshPrerequisites:
    """Private coordinator hook after the joint protected observation."""

    if (
        reader
        is not _BUSINESS_CUTOVER_ACTIVATION_COORDINATOR_READER_CAPABILITY
    ):
        _fail(
            "business_cutover_activation_coordinator_reader_invalid",
            "$.coordinator_reader",
        )
    return BusinessCutoverActivationFreshPrerequisites(
        snapshot,
        _reader=reader,
        _issuer=_FRESH_PREREQUISITE_ISSUER,
    )


def _unwrap_business_cutover_activation_fresh_prerequisites(
    value: Any,
) -> BusinessCutoverActivationPrerequisiteSnapshot:
    if (
        type(value) is not BusinessCutoverActivationFreshPrerequisites
        or getattr(value, "_issuer", None) is not _FRESH_PREREQUISITE_ISSUER
        or getattr(value, "_reader", None)
        is not _BUSINESS_CUTOVER_ACTIVATION_COORDINATOR_READER_CAPABILITY
        or type(getattr(value, "snapshot", None))
        is not BusinessCutoverActivationPrerequisiteSnapshot
    ):
        _fail(
            "business_cutover_activation_fresh_prerequisites_invalid",
            "$.prerequisites",
        )
    return value.snapshot


